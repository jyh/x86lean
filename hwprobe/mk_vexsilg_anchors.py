#!/usr/bin/env python3
"""hwprobe/mk_vexsilg_anchors.py — D374's kernel pins, as Lean rows DERIVED from mk_vexsilg_rows.py (D361's
mk_vexsile_anchors.py, its machinery unchanged, its subject the eleven VEX twins).

The rows the referee runs on a processor (`vexsile_probe.c` against `vexsilg_rows.h`) are the rows
`Tests/AnchorsVexSilG.lean` checks the model against: the SDM rule (`mk_simda_rows.rule`, wrapped and re-derived from
byte lists in mk_vexsilg_rows.py) and a processor. Nothing here is typed by hand, and nothing is read from x86lean or x86isa.

⛔ ALL ROWS ARE PINNED: ACL2 x86isa refuses every encoding (D374 P1). Each pin compares YMM3's FULL 256 bits, YMM1's and
YMM2's, RAX, MXCSR, the six flags and RIP. A register row writes no memory into the model; a memory row writes only the
qwords its operand spans. That memory is never written is `v8c_frame_binm`/`v8c_frame_binm256` (`Tests/AnchorsVexSilC`),
stated for every `VBinKind`.

    python3 hwprobe/mk_vexsilg_anchors.py            print the generated block
    python3 hwprobe/mk_vexsilg_anchors.py --check    exit 1 unless Tests/AnchorsVexSilG.lean carries it byte for byte
    python3 hwprobe/mk_vexsilg_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_vexsilg_rows.py's rule and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_vexsilg_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsVexSilG.lean")
BEGIN = ("-- ⟦D374 VEX-TWIN PINS BEGIN — GENERATED by hwprobe/mk_vexsilg_anchors.py; change mk_vexsilg_rows.py "
         "and regenerate⟧")
END = "-- ⟦D374 VEX-TWIN PINS END⟧"
TY = ("BitVec 256 × BitVec 256 × BitVec 256 × BitVec 64 × BitVec 32 × BitVec 64 × List (Nat × BitVec 64) × BitVec 64"
      " × BitVec 256 × BitVec 64 × BitVec 32")

# vexsilg_ops.S's registers: DEST %ymm3, SRC1 %ymm1 (VEX.vvvv), SRC2 %ymm2 or the memory operand at (%rbx).
EA = "{ base := some .rbx }"


def kind(legacy):
    """The `VBinKind` the legacy mnemonic is (X86/Syntax.lean, `VBinKind.mnemonic`), read from the anchors tables that
    already map them, so a second copy of that roster is not written here."""
    import mk_simda_anchors as A
    return {**A.KIND_A, **A.KIND_B}[legacy]


def instr(legacy, L, shape, bs):
    """The Lean instruction vexsilg_ops.S executes; its length the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    w = "" if L == 128 else "256"
    op = (".vexbin%s .%s .x3 .x1 .x2" % (w, kind(legacy)) if shape == "r"
          else ".vexbinm%s .%s .x3 .x1 %s" % (w, kind(legacy), EA))
    return "⟨.vex (%s), %d⟩" % (op, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, vmn, legacy, L, shape, bs in M.OPS:
        ins, n = instr(legacy, L, shape, bs)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_vexsilg_anchors: %s has no rows" % fn)
        used += len(fam)
        lines += ["", "set_option maxRecDepth 8000 in", "theorem d374_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s at VEX.%d" % (len(fam), fn, vmn, L)]
        for i, (nm, _fn, _l, _L, _s, y1, y2, y3, f, rax, mem, off, w3) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            mx, wrax, wfl = M.MX, rax, 0
            nb = _L // 8                                                # NOT `n`: that is the length
            span = range(off // 8, (off + nb - 1) // 8 + 1) if _s == "m" else range(0)
            qs = "[" + ", ".join("(%d, %s)" % (j, hx((mem >> (64 * j)) & ((1 << 64) - 1), 16)) for j in span) + "]"
            lines.append("    (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)%s  -- %s" % (
                hx(y1, 64), hx(y2, 64), hx(y3, 64), hx(f, 3), hx(mx, 4), hx(rax, 16), qs, hx(off, 2), hx(w3, 64),
                hx(wrax, 16), hx(mx | wfl, 4), sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (y1, y2, y3, f, mx, rax, mem, off, w3, wrax, wmx) =>",
                  "      let t := step %s (vgPre y1 y2 y3 f mx rax mem off)" % ins,
                  "      vgAgrees t %d y1 y2 f w3 wrax wmx) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_vexsilg_anchors: %d of mk_vexsilg_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (D374) are missing from Tests/AnchorsVexSilG.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- " + M.PLANT_ROW))
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_vexsilg_anchors selftest" if ok else "⛔ mk_vexsilg_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsVexSilG.lean carries mk_vexsilg_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
