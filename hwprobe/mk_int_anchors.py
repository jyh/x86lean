#!/usr/bin/env python3
"""hwprobe/mk_int_anchors.py — D330's and D334's kernel pins, as Lean rows DERIVED from mk_int_rows.py.

The rows the integer referee runs on a processor (`int_probe.c`) are the rows `Tests/Anchors.lean` checks the model
against, so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in mk_int_rows.py, and
a processor. Nothing here is typed by hand, and nothing is read from x86lean or from x86isa.

⛔ ONLY THE ROWS THE DIFFERENTIAL CANNOT CARRY ARE PINNED — mk_anchors.py's rule, applied to the integer rows:
  MULX        ACL2 x86isa refuses it at every pre-state (`scripts/oracle_availability.py`), so no vector can carry it.
              ALL of its rows are pinned: they are the only check of its numbers that this model has.
  ADCX, ADOX  x86isa executes both, and the vectors `adcx_*`/`adox_*` in Tests/Vectors.lean run each form over the 88
              pre-states, whose flag seeds put CF and OF in all four combinations. Those rows are CARRIED, and are
              refused here if the vector carrying their form is missing.
  W1c (D334)  ANDN, BEXTR, BLSMSK, BLSR, BZHI, PDEP, PEXT, RORX, MOVNTI: x86isa refuses every one, so ALL of their rows
              are pinned, each compared on the row's flag mask — in a second generated block that lives in a module of
              its own, Tests/AnchorsBmi.lean, so it is metered as its own kernel unit (arm (A) of the 2026-10-10 fork).

    python3 hwprobe/mk_int_anchors.py            print the generated W1b block (--w1c: the W1c block)
    python3 hwprobe/mk_int_anchors.py --check    exit 1 unless Tests/Anchors.lean (W1b) and Tests/AnchorsBmi.lean (W1c)
                                                 carry their blocks byte for byte
    python3 hwprobe/mk_int_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_int_rows.py's rules and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_int_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "Anchors.lean")
ANCHORS_C = os.path.join(ROOT, "Tests", "AnchorsBmi.lean")   # D334's block, in its own metered module
VECTORS = os.path.join(ROOT, "Tests", "Vectors.lean")
BEGIN = "-- ⟦W1b INTEGER PINS BEGIN — GENERATED by hwprobe/mk_int_anchors.py; change mk_int_rows.py and regenerate⟧"
END = "-- ⟦W1b INTEGER PINS END⟧"
BEGIN_C = "-- ⟦W1c INTEGER PINS BEGIN — GENERATED by hwprobe/mk_int_anchors.py; change mk_int_rows.py and regenerate⟧"
END_C = "-- ⟦W1c INTEGER PINS END⟧"

# (theorem, probe function, the instruction exactly as int_ops.S executes it)
MEM = "(.mem { base := some .rbx })"
FAMILIES = [
    ("w1b_mulxq_rr_pins", "i_mulxq_rr", "⟨.mulx .q .r8 .r9 (.reg .rcx), 5⟩"),
    ("w1b_mulxq_rm_pins", "i_mulxq_rm", "⟨.mulx .q .r8 .r9 %s, 5⟩" % MEM),
    ("w1b_mulxq_same_pins", "i_mulxq_same", "⟨.mulx .q .r8 .r8 (.reg .rcx), 5⟩"),
    ("w1b_mulxl_rr_pins", "i_mulxl_rr", "⟨.mulx .d .r8 .r9 (.reg .rcx), 5⟩"),
    ("w1b_mulxl_rm_pins", "i_mulxl_rm", "⟨.mulx .d .r8 .r9 %s, 5⟩" % MEM),
    ("w1b_mulxl_same_pins", "i_mulxl_same", "⟨.mulx .d .r8 .r8 (.reg .rcx), 5⟩"),
]
# The CARRIED forms, each with the differential vector that runs it over the 88 pre-states.
CARRIED = {
    "i_adcxq_rr": "adcx_rr_q", "i_adcxq_rm": "adcx_rm_q", "i_adcxl_rr": "adcx_rr_d", "i_adcxl_rm": "adcx_rm_d",
    "i_adoxq_rr": "adox_rr_q", "i_adoxq_rm": "adox_rm_q", "i_adoxl_rr": "adox_rr_d", "i_adoxl_rm": "adox_rm_d",
}
TY = "BitVec 64 × BitVec 64 × BitVec 64 × BitVec 64 × BitVec 64"
TY_C = "BitVec 64 × BitVec 64 × BitVec 64 × BitVec 64 × BitVec 64 × BitVec 64 × BitVec 64 × BitVec 64"


def w1c_instr(fn, bs, w, kind):
    """The Lean instruction int_ops.S executes for a W1c probe function — its operands are int_ops.S's register
    conventions (destination R8, RDX the VEX.vvvv source, RCX or [RBX] the r/m source), its length the declared
    bytes', and a RORX immediate the declared last byte (the model masks it, as the processor does)."""
    sz = ".q" if w == 64 else ".d"
    rm = MEM if "_rm" in fn else "(.reg .rcx)"
    n = len(bytearray.fromhex(bs))
    if kind == "andn":
        op = ".andn %s .r8 .rdx %s" % (sz, rm)
    elif kind in ("bextr", "bzhi"):
        op = ".%s %s .r8 %s .rdx" % (kind, sz, rm)
    elif kind in ("blsmsk", "blsr"):
        op = ".blsx %s %s .r8 %s" % ("true" if kind == "blsmsk" else "false", sz, rm)
    elif kind in ("pdep", "pext"):
        op = ".pbits %s %s .r8 .rdx %s" % ("true" if kind == "pext" else "false", sz, rm)
    elif kind == "rorx":
        op = ".rorx %s .r8 %s %d" % (sz, rm, bytearray.fromhex(bs)[-1])
    elif kind == "movnti":
        op = ".movnti %s %s .rax" % (sz, MEM)
    else:
        raise SystemExit("mk_int_anchors: no Lean instruction for %s" % fn)
    return "⟨%s, %d⟩" % (op, n), n


W1C_KINDS = ("andn", "bextr", "bzhi", "blsmsk", "blsr", "pdep", "pext", "rorx", "movnti")


def block_w1c():
    rs = rows()
    lines = [BEGIN_C]
    for _form, fn, bs, w, kind in M.OPS:
        if kind not in W1C_KINDS:
            continue
        instr, n = w1c_instr(fn, bs, w, kind)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_int_anchors: %s has no rows" % fn)
        lines += ["", "theorem w1c_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s" % (len(fam), fn, kind)]
        for i, (nm, _fn, a, b, d, f, w0, w1, two, wf, fm) in enumerate(fam):
            if not two:
                raise SystemExit("mk_int_anchors: %s does not compare R9, which every W1c row must" % nm)
            sep = "," if i + 1 < len(fam) else ""
            lines.append("    (%s, %s, %s, %s, %s, %s, %s, %s)%s  -- %s"
                         % (hx(a), hx(b), hx(d), hx(f, 3), hx(w0), hx(w1), hx(wf, 3), hx(fm, 3), sep, nm))
        lines.append("  ] : List (%s)).all" % TY_C)
        lines += ["    (fun (a, b, d, f, w0, w1, wf, fm) =>",
                  "      let t := step %s (w1cPre a b d f)" % instr,
                  "      w1cAgrees t %s %d w0 w1 wf fm) = true := by decide"
                  % ("true" if kind == "movnti" else "false", n)]
    lines += ["", END_C]
    return lines


def hx(v, digits=16):
    return "0x%0*x" % (digits, v)


def rows():
    M.build()
    return list(M.ROWS)


def block():
    rs = rows()
    vec = open(VECTORS, encoding="utf-8").read()
    missing = sorted(v for v in CARRIED.values() if ('id := "%s"' % v) not in vec)
    if missing:
        raise SystemExit("mk_int_anchors: rows are declared CARRIED by vectors Tests/Vectors.lean does not have: %s"
                         % missing)
    lines = [BEGIN]
    used = 0
    for thm, fn, instr in FAMILIES:
        fam = [r for r in rs if r[1] == fn]
        used += len(fam)
        lines += ["", "theorem %s :" % thm, "  ([  -- all %d of hwprobe's %s rows · x86isa refuses mulx" % (len(fam), fn)]
        for i, (n, _fn, a, b, d, f, w0, w1, two, wf, _fm) in enumerate(fam):
            if a != M.CANARY or not two:
                raise SystemExit("mk_int_anchors: %s does not have the MULX row shape this family checks" % n)
            sep = "," if i + 1 < len(fam) else ""
            lines.append("    (%s, %s, %s, %s, %s)%s  -- %s" % (hx(d), hx(b), hx(f, 3), hx(w0), hx(w1), sep, n))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (d, b, f, hi, lo) =>",
                  "      let t := step %s (w1bPre d b f)" % instr,
                  "      w1bAgrees t f hi lo) = true := by decide"]
    carried = sum(1 for r in rs if r[1] in CARRIED)
    w1c_fns = {fn for _f, fn, _b, _w, k in M.OPS if k in W1C_KINDS}
    w1c = sum(1 for r in rs if r[1] in w1c_fns)
    if used + carried + w1c != len(rs):
        raise SystemExit("mk_int_anchors: %d of mk_int_rows.py's rows are neither pinned nor carried"
                         % (len(rs) - used - carried - w1c))
    lines += ["", "-- %d further rows (ADCX, ADOX) are CARRIED by the differential vectors %s." %
              (carried, ", ".join(sorted(CARRIED.values()))), "", END]
    return lines


def extract(text, begin=BEGIN, end=END):
    ls = text.split("\n")
    if begin not in ls or end not in ls:
        return None
    i, j = ls.index(begin), ls.index(end)
    return ls[i:j + 1] if i < j else None


def compare(text, want, begin=BEGIN, end=END):
    got = extract(text, begin, end)
    if got is None:
        return ["the generated block's markers (%s) are missing from %s" % (begin[3:24], "Tests/AnchorsBmi.lean"
                if begin == BEGIN_C else "Tests/Anchors.lean")]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- mulxq_rr_ones_ones"))
    planted = row.replace("0xfffffffffffffffe,", "0xffffffffffffffff,", 1)
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected high half is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    # D334: the W1c block, by the same three arms, on a BZHI row whose expectation is the one D334 calls disputed.
    want_c = block_w1c()
    text_c = open(ANCHORS_C, encoding="utf-8").read()
    row_c = next(l for l in want_c if l.endswith("-- bzhiq_rr_ones_nw"))
    planted_c = row_c.replace("0xffffffffffffffff, 0xc3c3", "0x7fffffffffffffff, 0xc3c3", 1)
    arms += [
        ("control: the tracked W1c block is the generator's output", not compare(text_c, want_c, BEGIN_C, END_C)),
        ("the W1c plant really changes the row", planted_c != row_c),
        ("a W1c row's expected result is changed",
         bool(compare(text_c.replace(row_c, planted_c), want_c, BEGIN_C, END_C))),
        ("a W1c row is dropped", bool(compare(text_c.replace(row_c + "\n", ""), want_c, BEGIN_C, END_C))),
        ("the W1c END marker is lost", bool(compare(text_c.replace(END_C, "  --"), want_c, BEGIN_C, END_C))),
        ("the W1c block is NOT in Tests/Anchors.lean (it moved; a copy there would be metered twice)",
         extract(text, BEGIN_C, END_C) is None),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_int_anchors selftest" if ok else "⛔ mk_int_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want, want_c = block(), block_w1c()
        text = open(ANCHORS, encoding="utf-8").read()
        text_c = open(ANCHORS_C, encoding="utf-8").read()
        bad = compare(text, want) + compare(text_c, want_c, BEGIN_C, END_C)
        if extract(text, BEGIN_C, END_C) is not None:
            bad.append("the W1c block is in Tests/Anchors.lean too; it belongs to Tests/AnchorsBmi.lean alone")
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/Anchors.lean (W1b) and Tests/AnchorsBmi.lean (W1c) carry mk_int_anchors.py's blocks "
                  "byte for byte (%d + %d lines)"
                  % (len(want), len(want_c)))
        return 1 if bad else 0
    if "--w1c" in argv:
        print("\n".join(block_w1c()))
        return 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
