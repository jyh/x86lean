#!/usr/bin/env python3
"""hwprobe/mk_vexsilc_anchors.py — D350's kernel pins, as Lean rows DERIVED from mk_vexsilc_rows.py (V7's
mk_vexsil_anchors.py, restated for the second VEX-silicon path).

The rows the referee runs on a processor (`vexsilc_probe.c`) are the rows `Tests/AnchorsVexSilC.lean` checks the model
against, so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in mk_vexsilc_rows.py
(held row by row to an independent textbook there) and a processor. Nothing here is typed by hand, and nothing is read
from x86lean or from x86isa.

⛔ ALL ROWS ARE PINNED: ACL2 x86isa refuses all 12 encodings (`scripts/oracle_availability.py`, D350 prediction P1), so
these rows are the only check of the model's numbers for them. Each pin compares YMM3's FULL 256 bits (so VEX.128's
zeroing and VEX.256's high lane are both read), YMM1's and YMM2's 256 bits, RAX, MXCSR, the six flags and RIP. Only the qwords the memory operand SPANS are written into the model's memory (the probe
holds all 64 bytes); that memory is never written is proved ONCE, for every state, by the unit's frame theorems, not
re-checked per row, because the per-row read-back was more than half of this unit's kernel cost (D350, measured).

    python3 hwprobe/mk_vexsilc_anchors.py            print the generated block
    python3 hwprobe/mk_vexsilc_anchors.py --check    exit 1 unless Tests/AnchorsVexSilC.lean carries it byte for byte
    python3 hwprobe/mk_vexsilc_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_vexsilc_rows.py's rules and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_vexsilc_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsVexSilC.lean")
BEGIN = ("-- ⟦V8c VEX-MEMORY PINS BEGIN — GENERATED by hwprobe/mk_vexsilc_anchors.py; change mk_vexsilc_rows.py and "
         "regenerate⟧")
END = "-- ⟦V8c VEX-MEMORY PINS END⟧"
TY = ("BitVec 256 × BitVec 256 × BitVec 256 × BitVec 64 × BitVec 32 × BitVec 64 × List (Nat × BitVec 64) × BitVec 64"
      " × BitVec 256 × BitVec 64 × BitVec 32")

# vexsilc_ops.S's registers: DEST %ymm3, SRC1 %ymm1 (VEX.vvvv), the broadcast's register source %xmm2, memory at (%rbx).
BIN = {"vpmaddwd": ".maddwd", "vpmulhrsw": ".mulhrsw", "vpmaddubsw": ".maddubsw", "vpackssdw": ".packssdw"}
EA = "{ base := some .rbx }"


def instr(form, L, bs, imm):
    """The Lean instruction vexsilc_ops.S executes; its length the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    w = "" if L == 128 else "256"
    if form == "vpbroadcastd_r":
        op = ".vexbcastd%s .x3 .x2" % w
    elif form == "vpbroadcastd_m":
        op = ".vexbcastdm%s .x3 %s" % (w, EA)
    elif M.mnemonic(form) in BIN:
        op = ".vexbinm%s %s .x3 .x1 %s" % (w, BIN[M.mnemonic(form)], EA)
    else:
        raise SystemExit("mk_vexsilc_anchors: no Lean instruction for %s" % form)
    return "⟨.vex (%s), %d⟩" % (op, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, form, L, bs, imm in M.OPS:
        ins, n = instr(form, L, bs, imm)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_vexsilc_anchors: %s has no rows" % fn)
        used += len(fam)
        lines += ["", "set_option maxRecDepth 8000 in", "theorem v8c_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s at VEX.%d" % (len(fam), fn, M.mnemonic(form), L)]
        for i, (nm, _fn, _form, _L, y1, y2, y3, f, mx, rax, mem, off, w3, wrax, wmx) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            nb = 4 if _form == "vpbroadcastd_m" else (_L // 8 if M.is_mem(_form) else 0)   # NOT `n`: that is the length
            span = range(off // 8, (off + nb - 1) // 8 + 1) if nb else range(0)
            qs = "[" + ", ".join("(%d, %s)" % (j, hx((mem >> (64 * j)) & ((1 << 64) - 1), 16)) for j in span) + "]"
            lines.append("    (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)%s  -- %s" % (
                hx(y1, 64), hx(y2, 64), hx(y3, 64), hx(f, 3), hx(mx, 4), hx(rax, 16), qs, hx(off, 2), hx(w3, 64),
                hx(wrax, 16), hx(wmx, 4), sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (y1, y2, y3, f, mx, rax, mem, off, w3, wrax, wmx) =>",
                  "      let t := step %s (v8cPre y1 y2 y3 f mx rax mem off)" % ins,
                  "      v8cAgrees t %d y1 y2 f w3 wrax wmx) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_vexsilc_anchors: %d of mk_vexsilc_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (V8c) are missing from Tests/AnchorsVexSilC.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- " + M.PLANT_ROW))
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_vexsilc_anchors selftest" if ok else "⛔ mk_vexsilc_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsVexSilC.lean carries mk_vexsilc_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
