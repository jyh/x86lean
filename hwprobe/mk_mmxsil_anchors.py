#!/usr/bin/env python3
"""hwprobe/mk_mmxsil_anchors.py — D407's kernel pins, as Lean rows DERIVED from mk_mmxsil_rows.py.

The rows the MMX silicon referee runs (`mmxsil_probe.c`) are the rows `Tests/AnchorsMmxSil.lean` checks the model against,
so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in mk_mmxsil_rows.py, and a
processor. Nothing here is typed by hand, and nothing is read from x86lean or from x86isa.

    python3 hwprobe/mk_mmxsil_anchors.py            print the generated block
    python3 hwprobe/mk_mmxsil_anchors.py --write    write it between the markers of Tests/AnchorsMmxSil.lean
    python3 hwprobe/mk_mmxsil_anchors.py --check    exit 1 unless Tests/AnchorsMmxSil.lean carries it byte for byte
    python3 hwprobe/mk_mmxsil_anchors.py --selftest the --check arm must go red on a changed row, a dropped row and a lost marker
    add --set-b to any of these for D408's set B, whose pins are Tests/AnchorsMmxSilB.lean

⛔ `--check` RAN NOWHERE until D408: D407 shipped this generator with no `--selftest` and with neither arm in ci.yml or
preflight.sh, while the Lean file's header said "`--check` gates it byte for byte". Every sibling generator ran both.
D408 added the selftest and wired both arms, for both sets.

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is the rules
and the processor's reading; what makes the MODEL right is the kernel. The paddw control rows are the probe's, not pins.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_mmxsil_rows as M  # noqa: E402

# Per set: the Lean file, its markers, the theorem/helper prefix, and the VBinKind of each mnemonic.
SETS = {
    False: dict(lean=os.path.join(ROOT, "Tests", "AnchorsMmxSil.lean"), tag="d407",
                begin="-- ⟦D407 MMX SILICON PINS BEGIN — GENERATED by hwprobe/mk_mmxsil_anchors.py; change mk_mmxsil_rows.py and regenerate⟧",
                end="-- ⟦D407 MMX SILICON PINS END⟧",
                kind={"pmaxsw": ".maxsw", "psadbw": ".sadbw", "pavgb": ".avgb"}),
    True: dict(lean=os.path.join(ROOT, "Tests", "AnchorsMmxSilB.lean"), tag="d408",
               begin="-- ⟦D408 MMX SILICON PINS BEGIN — GENERATED by hwprobe/mk_mmxsil_anchors.py --set-b; change mk_mmxsil_rows.py and regenerate⟧",
               end="-- ⟦D408 MMX SILICON PINS END⟧",
               kind={"pminsw": ".minsw", "pavgw": ".avgw", "pmulhrsw": ".mulhrsw", "pmaddubsw": ".maddubsw",
                     "pmulhuw": ".mulhuw"}),
}
# The encoded length, which the row's RIP check reads: `NP 0F xx /r` is 3 bytes at both shapes here (the memory operand is
# [RBX], no SIB, no displacement); the SSSE3 forms are `NP 0F 38 xx /r`, 4; pshufw adds its imm8, 4.
LENGTH = {"pshufw": 4, "pmulhrsw": 4, "pmaddubsw": 4}
LEAN = SETS[False]["lean"]
BEGIN = SETS[False]["begin"]
END = SETS[False]["end"]
KIND = SETS[False]["kind"]


def instr(mn, shape, set_b=False):
    """The instruction a row runs, as a Lean term over the row's `i` (the imm8, pshufw only)."""
    if mn == "pshufw":
        return "⟨.mmpshufw .m0 .m1 i, 4⟩" if shape == "rr" else "⟨.mmpshufwm .m0 { base := some .rbx } i, 4⟩"
    k = SETS[set_b]["kind"][mn]
    n = LENGTH.get(mn, 3)
    return f"⟨.mmbin {k} .m0 .m1, {n}⟩" if shape == "rr" else f"⟨.mmbinm {k} .m0 {{ base := some .rbx }}, {n}⟩"


def block(set_b=False):
    S = SETS[set_b]
    tag = S["tag"]
    rows = [r for r in M.rows(set_b) if r[1] != "paddw"]
    out = [S["begin"]]
    for mn in (M.MNEMONICS_B if set_b else M.MNEMONICS):
        for shape in ("rr", "rm"):
            rs = [r for r in rows if r[1] == mn and r[2] == shape]
            n = LENGTH.get(mn, 3)
            out.append(f"theorem {tag}_{mn}_{shape}_pins :")
            out.append(f"  ([  -- all {len(rs)} of hwprobe's {mn}_{shape} rows · x86isa names no handler for the NP form")
            for j, (form, _mn, _sh, a, b, imm, want) in enumerate(rs):
                sep = "," if j + 1 < len(rs) else ""
                out.append(f"    (0x{a:016x}, 0x{b:016x}, 0x{imm:02x}, 0x{want:016x}){sep}  -- {form}")
            out.append("   ] : List (BitVec 64 × BitVec 64 × BitVec 8 × BitVec 64)).all")
            out.append(f"    (fun (a, b, i, w) => {tag}Agrees (step {instr(mn, shape, set_b)} ({tag}Pre a b)) {n} b w) = true := by")
            out.append("  decide")
            out.append("")
    out.append(S["end"])
    return "\n".join(out) + "\n"


def current(set_b=False, text=None):
    S = SETS[set_b]
    s = open(S["lean"], encoding="utf-8").read() if text is None else text
    i, j = s.find(S["begin"]), s.find(S["end"])
    if i < 0 or j < 0:
        return None, s
    return s[i:j + len(S["end"])] + "\n", s


def selftest(set_b=False):
    """The --check comparison must go RED on each defect it exists to catch, and GREEN on the tracked file."""
    S = SETS[set_b]
    want = block(set_b)
    text = open(S["lean"], encoding="utf-8").read()
    rows = [l for l in want.split("\n") if l.startswith("    (0x")]
    row = rows[len(rows) // 2]
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail

    def stale(t):
        cur, _ = current(set_b, t)
        return cur != want

    arms = [
        ("control: the tracked block is the generator's output", not stale(text)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row and text.count(row) == 1),
        ("a row's expected result is changed", stale(text.replace(row, planted))),
        ("a row is dropped", stale(text.replace(row + "\n", ""))),
        ("the END marker is lost", stale(text.replace(S["end"], "  --"))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    label = "mk_mmxsil_anchors" + (" --set-b" if set_b else "")
    print(("✅ " + label + " selftest") if ok else ("⛔ " + label + " selftest FAILED"))
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    set_b = "--set-b" in argv
    S = SETS[set_b]
    if "--selftest" in argv:
        return selftest(set_b)
    b = block(set_b)
    if "--write" in argv:
        cur, s = current(set_b)
        if cur is None:
            print("⛔ markers not found in " + S["lean"])
            return 2
        i, j = s.find(S["begin"]), s.find(S["end"])
        open(S["lean"], "w", encoding="utf-8").write(s[:i] + b + s[j + len(S["end"]) + 1:])
        print(f"wrote {b.count('theorem')} theorems → {S['lean']}")
        return 0
    if "--check" in argv:
        cur, _ = current(set_b)
        if cur is None:
            print("⛔ markers not found: the generated block is UNREAD, not equal")
            return 1
        ok = cur == b
        print(("mmxsil-anchors" + (" (set B)" if set_b else "") + ": " + ("CLEAN — " if ok else "⛔ STALE — "))
              + f"{b.count('theorem')} theorems, {sum(1 for r in M.rows(set_b) if r[1] != 'paddw')} rows")
        return 0 if ok else 1
    sys.stdout.write(b)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
