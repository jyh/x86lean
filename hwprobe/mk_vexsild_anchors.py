#!/usr/bin/env python3
"""hwprobe/mk_vexsild_anchors.py — D354's kernel pins, as Lean rows DERIVED from mk_vexsild_rows.py (V8c's
mk_vexsilc_anchors.py, restated for the VEX move memory forms and their FAULT rows).

The rows the referee runs on a processor (`vexsild_probe.c`) are the rows `Tests/AnchorsVexSilD.lean` checks the model
against, so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in mk_vexsild_rows.py (held
row by row to an independent textbook there) and a processor. Nothing here is typed by hand, and nothing is read from
x86lean or from x86isa.

Every row is pinned, the value rows AND the fault rows: x86isa executes the aligned kinds' misaligned encodings (D354 P1),
so for the 30 fault rows these pins and the processor are the only check that the model raises #GP. A value row compares
YMM3's 256 bits, YMM1, YMM2, RAX, MXCSR, the six flags, RIP, and the qwords the access spans (a store's written bytes and
their neighbours in those qwords); a fault row requires a `byDesign` halt and the spanned qwords unchanged.

    python3 hwprobe/mk_vexsild_anchors.py            print the generated block
    python3 hwprobe/mk_vexsild_anchors.py --check    exit 1 unless Tests/AnchorsVexSilD.lean carries it byte for byte
    python3 hwprobe/mk_vexsild_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_vexsild_rows.py's rules and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_vexsild_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsVexSilD.lean")
BEGIN = ("-- ⟦V9b VEX-MOVE PINS BEGIN — GENERATED by hwprobe/mk_vexsild_anchors.py; change mk_vexsild_rows.py and "
         "regenerate⟧")
END = "-- ⟦V9b VEX-MOVE PINS END⟧"
TY = ("BitVec 256 × BitVec 256 × BitVec 256 × BitVec 64 × BitVec 32 × BitVec 64 × List (Nat × BitVec 64) × BitVec 64"
      " × Bool × BitVec 256 × List (Nat × BitVec 64)")

# vexsild_ops.S's registers: a load's DEST %ymm3, a store's SRC %ymm2, memory at (%rbx).
EA = "{ base := some .rbx }"
M64 = (1 << 64) - 1


def instr(kind, L, d, bs):
    """The Lean instruction vexsild_ops.S executes; its length the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    w = "" if L == 128 else "256"
    op = (".vexload%s .%s .x3 %s" % (w, kind, EA)) if d == "ld" else (".vexstore%s .%s %s .x2" % (w, kind, EA))
    return "⟨.vex (%s), %d⟩" % (op, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def span(mem, off, nb):
    return "[" + ", ".join("(%d, %s)" % (j, hx((mem >> (64 * j)) & M64, 16))
                           for j in range(off // 8, (off + nb - 1) // 8 + 1)) + "]"


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, kind, L, d, bs in M.OPS:
        ins, n = instr(kind, L, d, bs)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_vexsild_anchors: %s has no rows" % fn)
        used += len(fam)
        nf = sum(1 for r in fam if r[13])
        lines += ["", "set_option maxRecDepth 8000 in", "theorem v9b_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows (%d of them FAULT rows)" % (len(fam), fn, nf)]
        for i, (nm, _fn, _k, _L, _d, y1, y2, y3, f, mx, rax, mem, off, fault, w3, wmem) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            nb = _L // 8
            lines.append("    (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)%s  -- %s" % (
                hx(y1, 64), hx(y2, 64), hx(y3, 64), hx(f, 3), hx(mx, 4), hx(rax, 16), span(mem, off, nb), hx(off, 2),
                "true" if fault else "false", hx(w3, 64), span(wmem, off, nb), sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (y1, y2, y3, f, mx, rax, mem, off, fault, w3, wmem) =>",
                  "      let t := step %s (v9bPre y1 y2 y3 f mx rax mem off)" % ins,
                  "      v9bAgrees t %d y1 y2 f mx rax fault w3 wmem) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_vexsild_anchors: %d of mk_vexsild_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (V9b) are missing from Tests/AnchorsVexSilD.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- " + M.PLANT_ROW))
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_vexsild_anchors selftest" if ok else "⛔ mk_vexsild_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsVexSilD.lean carries mk_vexsild_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
