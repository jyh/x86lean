#!/usr/bin/env python3
"""hwprobe/mk_vexsilm_anchors.py — D394's kernel pins for the VEX scalar floating-point forms, as Lean rows DERIVED from
mk_vexsilm_rows.py (D393's mk_vexsill_anchors.py, its machinery unchanged, its subject wave G's ten mnemonics, and ONE
column added: the buffer's expected qwords, because the two store forms write memory).

The rows the referee runs on a processor (`vexsilm_probe.c` against `vexsilm_rows.h`) are the rows
`Tests/AnchorsVexSilM.lean` checks the model against. Nothing here is typed by hand, and nothing is read from x86lean or
x86isa.

⛔ ALL ROWS ARE PINNED: ACL2 x86isa refuses every encoding (D394 P1 and reading 0). Each pin compares YMM3's FULL 256 bits,
YMM1's and YMM2's, RAX, MXCSR (mx OR the flags raised), the six flags and RIP, and, at a memory row, the qwords its operand
spans AFTER the step (unchanged for a load or an arithmetic source; written for a store).

    python3 hwprobe/mk_vexsilm_anchors.py            print the generated block
    python3 hwprobe/mk_vexsilm_anchors.py --check    exit 1 unless Tests/AnchorsVexSilM.lean carries it byte for byte
    python3 hwprobe/mk_vexsilm_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_vexsilm_rows.py's rule and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_vexsilm_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsVexSilM.lean")
BEGIN = ("-- ⟦D394 VEX-SCALAR-FP PINS BEGIN — GENERATED by hwprobe/mk_vexsilm_anchors.py; change mk_vexsilm_rows.py "
         "and regenerate⟧")
END = "-- ⟦D394 VEX-SCALAR-FP PINS END⟧"
TY = ("BitVec 256 × BitVec 256 × BitVec 256 × BitVec 64 × BitVec 32 × BitVec 64 × List (Nat × BitVec 64) × BitVec 64"
      " × BitVec 256 × BitVec 64 × BitVec 32 × List (Nat × BitVec 64)")

# vexsilm_ops.S's registers: DEST %xmm3 (the store's source), SRC1 %xmm1 (VEX.vvvv), SRC2 %xmm2 or the operand at (%rbx).
EA = "{ base := some .rbx }"


def instr(kind, w, shape, bs):
    """The Lean instruction vexsilm_ops.S executes; its length the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    sz = ".d" if w == 32 else ".q"
    if kind == "movs":
        op = {"r": ".vexmovs %s .x3 .x1 .x2" % sz, "l": ".vexmovsld %s .x3 %s" % (sz, EA),
              "s": ".vexmovsst %s %s .x3" % (sz, EA)}[shape]
    else:
        op = (".vexarith .%s %s .x3 .x1 .x2" % (kind, sz) if shape == "r"
              else ".vexarithm .%s %s .x3 .x1 %s" % (kind, sz, EA))
    return "⟨.vex (%s), %d⟩" % (op, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def span(shape, off, w):
    return range(off // 8, (off + w // 8 - 1) // 8 + 1) if shape != "r" else range(0)


def qs(mem, js):
    return "[" + ", ".join("(%d, %s)" % (j, hx((mem >> (64 * j)) & ((1 << 64) - 1), 16)) for j in js) + "]"


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, kind, w, shape, bs in M.OPS:
        ins, n = instr(kind, w, shape, bs)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_vexsilm_anchors: %s has no rows" % fn)
        used += len(fam)
        lines += ["", "set_option maxRecDepth 8000 in", "theorem d394_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s" % (len(fam), fn, M.mnem(kind, w))]
        for i, (nm, _fn, _k, _w, _s, _rc, mx, y1, y2, y3, f, rax, mem, off, w3, wf, wmem) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            js = span(_s, off, _w)
            lines.append("    (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)%s  -- %s" % (
                hx(y1, 64), hx(y2, 64), hx(y3, 64), hx(f, 3), hx(mx, 4), hx(rax, 16), qs(mem, js), hx(off, 2),
                hx(w3, 64), hx(rax, 16), hx(mx | wf, 4), qs(wmem, js), sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (y1, y2, y3, f, mx, rax, mem, off, w3, wrax, wmx, wq) =>",
                  "      let t := step %s (vmPre y1 y2 y3 f mx rax mem off)" % ins,
                  "      vmAgrees t %d y1 y2 f w3 wrax wmx wq) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_vexsilm_anchors: %d of mk_vexsilm_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (D394) are missing from Tests/AnchorsVexSilM.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- " + M.PLANT_ROW))
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_vexsilm_anchors selftest" if ok else "⛔ mk_vexsilm_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsVexSilM.lean carries mk_vexsilm_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
