#!/usr/bin/env python3
"""hwprobe/mk_aes_anchors.py — D342's kernel pins, as Lean rows DERIVED from mk_aes_rows.py.

The rows the AES-NI/CLMUL/VEX referee runs on a processor (`aes_probe.c`) are the rows `Tests/AnchorsAes.lean` checks
the model against, so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in
mk_aes_rows.py (and, for its known-answer rows, a textbook FIPS-197 AES-128 and a textbook carry-less product), and a
processor. Nothing here is typed by hand, and nothing is read from x86lean or from x86isa.

⛔ ALL ROWS ARE PINNED: ACL2 x86isa refuses all nine mnemonics at every pre-state (`scripts/oracle_availability.py`,
D342 prediction 1), so these rows are the only check of the model's numbers for them. Each pin compares the
destination's FULL 256 bits (`getXmm` and `getYmmHi`), the two other registers' 256 bits, the six flags and RIP.

    python3 hwprobe/mk_aes_anchors.py            print the generated block
    python3 hwprobe/mk_aes_anchors.py --check    exit 1 unless Tests/AnchorsAes.lean carries it byte for byte
    python3 hwprobe/mk_aes_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_aes_rows.py's rules and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_aes_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsAes.lean")
BEGIN = "-- ⟦V4 AES PINS BEGIN — GENERATED by hwprobe/mk_aes_anchors.py; change mk_aes_rows.py and regenerate⟧"
END = "-- ⟦V4 AES PINS END⟧"
TY = "BitVec 256 × BitVec 256 × BitVec 256 × BitVec 64 × BitVec 256"
M128 = (1 << 128) - 1


def instr(fn, bs, mn, imm):
    """The Lean instruction aes_ops.S executes (legacy: DEST %xmm1, SRC %xmm2; VEX: DEST %xmm3, SRC1 %xmm1, SRC2
    %xmm2; the VEX shifts: DEST %xmm3, SRC %xmm1); its length the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    op = {"aesenc": ".vaes .enc .x1 .x2", "aesenclast": ".vaes .enclast .x1 .x2",
          "vaesenc": ".vexaes .enc .x3 .x1 .x2", "vaesenclast": ".vexaes .enclast .x3 .x1 .x2",
          "vpshufb": ".vexshufb .x3 .x1 .x2",
          "vpclmulqdq": ".vexclmul .x3 .x1 .x2 0x%02x" % (imm or 0),
          "vpalignr": ".vexalignr .x3 .x1 .x2 0x%02x" % (imm or 0),
          "vpslldq": ".vexshiftdq true .x3 .x1 0x%02x" % (imm or 0),
          "vpsrldq": ".vexshiftdq false .x3 .x1 0x%02x" % (imm or 0)}[mn]
    return "⟨%s, %d⟩" % (op, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, mn, vex, bs, imm in M.OPS:
        ins, n = instr(fn, bs, mn, imm)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_aes_anchors: %s has no rows" % fn)
        used += len(fam)
        # The 34-row AES families exceed the elaborator's default recursion depth while `decide` unfolds the list
        # (`Tests/Anchors.lean`'s precedent: raised per theorem, never file-wide).
        lines += ["", "set_option maxRecDepth 8000 in", "theorem v4_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s" % (len(fam), fn, mn)]
        for i, (nm, _fn, _mn, _v, y1, y2, y3, _imm, f, w) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            lines.append("    (%s, %s, %s, %s, %s)%s  -- %s" % (hx(y1, 64), hx(y2, 64), hx(y3, 64), hx(f, 3),
                                                             hx(w, 64), sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (y1, y2, y3, f, w) =>",
                  "      let t := step %s (v4Pre y1 y2 y3 f)" % ins,
                  "      v4Agrees t %d %s y1 y2 y3 f w) = true := by decide" % (n, ".x3" if vex else ".x1")]
    if used != len(rs):
        raise SystemExit("mk_aes_anchors: %d of mk_aes_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (V4) are missing from Tests/AnchorsAes.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- aesenc_kat_b_r1"))
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_aes_anchors selftest" if ok else "⛔ mk_aes_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsAes.lean carries mk_aes_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
