#!/usr/bin/env python3
"""hwprobe/mk_sha_anchors.py — D338's kernel pins, as Lean rows DERIVED from mk_sha_rows.py.

The rows the SHA-NI referee runs on a processor (`sha_probe.c`) are the rows `Tests/AnchorsSha.lean` checks the model
against, so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in mk_sha_rows.py (and,
for its known-answer rows, a textbook FIPS 180-4 SHA-256), and a processor. Nothing here is typed by hand, and nothing
is read from x86lean or from x86isa.

⛔ ALL 148 ROWS ARE PINNED: ACL2 x86isa refuses all three mnemonics at every pre-state
(`scripts/oracle_availability.py`, D338 prediction 1), so no differential vector can carry any of them, and these rows
are the only check of the model's numbers for them.

    python3 hwprobe/mk_sha_anchors.py            print the generated block
    python3 hwprobe/mk_sha_anchors.py --check    exit 1 unless Tests/AnchorsSha.lean carries it byte for byte
    python3 hwprobe/mk_sha_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_sha_rows.py's rules and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_sha_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsSha.lean")
BEGIN = "-- ⟦V2 SHA PINS BEGIN — GENERATED by hwprobe/mk_sha_anchors.py; change mk_sha_rows.py and regenerate⟧"
END = "-- ⟦V2 SHA PINS END⟧"

# The `ShaKind` kind each mnemonic is (X86/Syntax.lean, `ShaKind.mnemonic`).
KIND = {"sha256msg1": "msg1", "sha256msg2": "msg2", "sha256rnds2": "rnds2"}
TY = "BitVec 128 × BitVec 128 × BitVec 128 × BitVec 64 × BitVec 128"


def instr(fn, bs, mn, shape):
    """The Lean instruction sha_ops.S executes: DEST %xmm1, SRC2 %xmm2 or the m128 at [RBX] (XMM0 implicit); its length
    the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    op = (".vsha .%s .x1 .x2" % KIND[mn] if shape == "xx"
          else ".vsham .%s .x1 { base := some .rbx }" % KIND[mn])
    return "⟨%s, %d⟩" % (op, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def block():
    M.build()
    rs = list(M.ROWS)
    if set(KIND) != {mn for mn, _o in M.MNEMONICS}:
        raise SystemExit("mk_sha_anchors: KIND does not name exactly mk_sha_rows.py's mnemonics")
    lines = [BEGIN]
    used = 0
    for _form, fn, bs, mn, shape in M.OPS:
        ins, n = instr(fn, bs, mn, shape)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_sha_anchors: %s has no rows" % fn)
        used += len(fam)
        lines += ["", "theorem v2_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s" % (len(fam), fn, mn)]
        for i, (nm, _fn, _mn, a, b, k, f, w) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            lines.append("    (%s, %s, %s, %s, %s)%s  -- %s" % (hx(a, 32), hx(b, 32), hx(k, 32), hx(f, 3), hx(w, 32),
                                                             sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (a, b, k, f, w) =>",
                  "      let t := step %s (v2Pre a b k f)" % ins,
                  "      v2Agrees t %d b k f w) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_sha_anchors: %d of mk_sha_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (V2) are missing from Tests/AnchorsSha.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- sha256msg2_xx_kat_abc"))
    planted = row.replace("0x600003c67da86405000f000061626380)", "0x600003c67da86405000f000061626381)", 1)
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_sha_anchors selftest" if ok else "⛔ mk_sha_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsSha.lean carries mk_sha_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
