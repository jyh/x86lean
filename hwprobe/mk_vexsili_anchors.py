#!/usr/bin/env python3
"""hwprobe/mk_vexsili_anchors.py — D376's kernel pins, as Lean rows DERIVED from mk_vexsili_rows.py (D375's
mk_vexsilh_anchors.py, its machinery unchanged, its subject `movntdqa` and the VEX.128 half-moves).

The rows the referee runs on a processor (`vexsilf_probe.c` against `vexsili_rows.h`) are the rows
`Tests/AnchorsVexSilI.lean` checks the model against: the SDM rule in mk_vexsili_rows.py (re-derived there from byte
lists) and a processor. Nothing here is typed by hand, and nothing is read from x86lean or x86isa.

⛔ ALL ROWS ARE PINNED: ACL2 x86isa refuses all nine encodings (D376 P1). Each pin compares YMM3's FULL 256 bits, YMM1's
and YMM2's, RAX, the six flags and RIP; a row writes into the model only the qwords its operand spans (16 bytes for
`movntdqa`, 8 for a half-move), and a STORE row compares exactly those qwords with the expected buffer's.

    python3 hwprobe/mk_vexsili_anchors.py            print the generated block
    python3 hwprobe/mk_vexsili_anchors.py --check    exit 1 unless Tests/AnchorsVexSilI.lean carries it byte for byte
    python3 hwprobe/mk_vexsili_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_vexsili_rows.py's rule and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_vexsili_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsVexSilI.lean")
BEGIN = ("-- ⟦D376 HALF-MOVE PINS BEGIN — GENERATED by hwprobe/mk_vexsili_anchors.py; change "
         "mk_vexsili_rows.py and regenerate⟧")
END = "-- ⟦D376 HALF-MOVE PINS END⟧"
TY = ("BitVec 256 × BitVec 256 × BitVec 256 × BitVec 64 × BitVec 64 × List (Nat × BitVec 64) × BitVec 64"
      " × BitVec 256 × BitVec 64 × List (Nat × BitVec 64)")

# vexsili_ops.S's registers (the declared bytes' ModRM and VEX.vvvv): DEST %xmm3, a load's SRC1 and a store's SRC
# %xmm1, memory at (%rbx).
EA = "{ base := some .rbx }"


def instr(mn, kind, half, bs):
    """The Lean instruction vexsili_ops.S executes; its length the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    if kind == "nt":
        return "⟨.vloadnt .x3 %s, %d⟩" % (EA, n), n
    h = {"h": ".hi", "l": ".lo"}[half]
    k = ".pd" if mn.endswith("pd") else ".ps"
    o = (".vexloadq %s %s .x3 .x1 %s" % (h, k, EA) if kind == "ld" else ".vexstoreq %s %s %s .x1" % (h, k, EA))
    return "⟨.vex (%s), %d⟩" % (o, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, mn, kind, half, bs in M.OPS:
        ins, n = instr(mn, kind, half, bs)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_vexsili_anchors: %s has no rows" % fn)
        used += len(fam)
        lines += ["", "set_option maxRecDepth 8000 in", "theorem vi_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s" % (len(fam), fn, mn)]
        for i, (nm, _fn, _k, _h, y1, y2, y3, f, rax, mem, off, w3, wmem) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            wrax, nb = rax, (16 if _k == "nt" else 8)
            span = range(off // 8, (off + nb - 1) // 8 + 1)
            qs = lambda m: "[" + ", ".join("(%d, %s)" % (j, hx((m >> (64 * j)) & ((1 << 64) - 1), 16))
                                           for j in span) + "]"
            mq = qs(mem)
            wq = qs(wmem) if _k == "st" else "[]"
            lines.append("    (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)%s  -- %s" % (
                hx(y1, 64), hx(y2, 64), hx(y3, 64), hx(f, 3), hx(rax, 16), mq, hx(off, 2), hx(w3, 64),
                hx(wrax, 16), wq, sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (y1, y2, y3, f, rax, mem, off, w3, wrax, wq) =>",
                  "      let t := step %s (viPre y1 y2 y3 f rax mem off)" % ins,
                  "      viAgrees t %d y1 y2 f w3 wrax wq) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_vexsili_anchors: %d of mk_vexsili_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (D376) are missing from Tests/AnchorsVexSilI.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- " + M.PLANT_ROW))
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_vexsili_anchors selftest" if ok else "⛔ mk_vexsili_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsVexSilI.lean carries mk_vexsili_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
