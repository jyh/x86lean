#!/usr/bin/env python3
"""hwprobe/mk_shuf_anchors.py — D336's kernel pins, as Lean rows DERIVED from mk_shuf_rows.py.

The rows the V1b referee runs on a processor (`shuf_probe.c`) are the rows `Tests/AnchorsShuf.lean` checks the model
against, so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in mk_shuf_rows.py, and
a processor. Nothing here is typed by hand, and nothing is read from x86lean or from x86isa.

⛔ ALL ROWS ARE PINNED: ACL2 x86isa refuses PSHUFB, PALIGNR, PINSRD, PINSRQ, PEXTRD and PEXTRQ at every pre-state
(`scripts/oracle_availability.py`, D336), so no differential vector can carry any of them and these rows are the only
check of the model's numbers.

    python3 hwprobe/mk_shuf_anchors.py            print the generated V1b block
    python3 hwprobe/mk_shuf_anchors.py --check    exit 1 unless Tests/AnchorsShuf.lean carries the block byte for byte
    python3 hwprobe/mk_shuf_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_shuf_rows.py's rules and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_shuf_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsShuf.lean")
BEGIN = "-- ⟦V1b SHUFFLE PINS BEGIN — GENERATED by hwprobe/mk_shuf_anchors.py; change mk_shuf_rows.py and regenerate⟧"
END = "-- ⟦V1b SHUFFLE PINS END⟧"
MEM = "{ base := some .rbx }"
TY = "BitVec 128 × BitVec 128 × BitVec 64 × BitVec 64 × BitVec 128 × BitVec 64"


def instr(fn, bs, mn, shape, imm):
    """The Lean instruction shuf_ops.S executes for a probe function — its operands are shuf_ops.S's register
    conventions (XMM0 the destination, XMM1 or [RBX] the source, RCX the GPR source, RAX PEXTR's destination), its
    length the declared bytes', and the imm8 the declared last byte."""
    n = len(bytearray.fromhex(bs))
    if mn == "pshufb":
        op = ".vshufb .x0 .x1" if shape == "rr" else ".vshufbm .x0 %s" % MEM
    elif mn == "palignr":
        op = (".valignr .x0 .x1 %d" % imm) if shape == "rr" else (".valignrm .x0 %s %d" % (MEM, imm))
    elif mn in ("pinsrd", "pinsrq"):
        sz = ".d" if mn == "pinsrd" else ".q"
        src = "(.reg .rcx)" if shape == "rr" else "(.mem %s)" % MEM
        op = ".vinsr %s .x0 %s %d" % (sz, src, imm)
    elif mn in ("pextrd", "pextrq"):
        op = ".vextr %s .rax .x1 %d" % (".d" if mn == "pextrd" else ".q", imm)
    else:
        raise SystemExit("mk_shuf_anchors: no Lean instruction for %s" % fn)
    return "⟨%s, %d⟩" % (op, n), n


def hx(v, digits=16):
    return "0x%0*x" % (digits, v)


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, bs, mn, shape, imm in M.OPS:
        ins, n = instr(fn, bs, mn, shape, imm)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_shuf_anchors: %s has no rows" % fn)
        used += len(fam)
        lines += ["", "theorem v1b_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s" % (len(fam), fn, mn)]
        for i, (nm, _fn, a, b, g, f, r, ax) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            lines.append("    (%s, %s, %s, %s, %s, %s)%s  -- %s"
                         % (hx(a, 32), hx(b, 32), hx(g), hx(f, 3), hx(r, 32), hx(ax), sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (a, b, g, f, wr, wax) =>",
                  "      let t := step %s (v1bPre a b g f)" % ins,
                  "      v1bAgrees t %d f wr wax) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_shuf_anchors: %d of mk_shuf_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (V1b) are missing from Tests/AnchorsShuf.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- pextrd_rr_i1_p1"))
    planted = row.replace(", 0x00000000b7b6b5b4)", ", 0x00000001b7b6b5b4)", 1)
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected RAX is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_shuf_anchors selftest" if ok else "⛔ mk_shuf_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsShuf.lean carries mk_shuf_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
