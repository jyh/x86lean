#!/usr/bin/env python3
"""hwprobe/mk_vexsilf_anchors.py — D371's kernel pins, as Lean rows DERIVED from mk_vexsilf_rows.py (D361's
mk_vexsile_anchors.py, restated for VEX `vmovd`/`vmovq`).

The rows the referee runs on a processor (`vexsilf_probe.c`) are the rows `Tests/AnchorsVexSilF.lean` checks the model
against, so a pinned expectation has two origins before the kernel sees it: the SDM rule stated in mk_vexsilf_rows.py
(held row by row to an independent textbook there) and a processor. Nothing here is typed by hand, and nothing is read
from x86lean or from x86isa.

⛔ ALL ROWS ARE PINNED: ACL2 x86isa refuses these encodings (`oracle_availability.py`'s `measure()`, D371 P1), so
these rows are the only check of the model's numbers for them. Each pin compares YMM3's FULL 256 bits (so the VEX.128
zeroing is read), YMM1's and YMM2's 256 bits, RAX, MXCSR, the six flags and RIP. Only the qwords the memory operand
SPANS are written into the model's memory. ⭐ A STORE ROW ALSO READS THOSE QWORDS BACK and compares them with the
expected buffer's (the rows of the other forms carry no read-back: their frame theorems state `mem` unchanged).

    python3 hwprobe/mk_vexsilf_anchors.py            print the generated block
    python3 hwprobe/mk_vexsilf_anchors.py --check    exit 1 unless Tests/AnchorsVexSilF.lean carries it byte for byte
    python3 hwprobe/mk_vexsilf_anchors.py --selftest the check refuses a planted row, a dropped row and a lost marker

⚠️ `--check` is TRANSPORT: it proves the Lean table is this generator's output. What makes the rows right is
mk_vexsilf_rows.py's rules and the processor's reading; what makes the MODEL right is the kernel.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import portable as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mk_vexsilf_rows as M  # noqa: E402

ANCHORS = os.path.join(ROOT, "Tests", "AnchorsVexSilF.lean")
BEGIN = ("-- ⟦D371 VEX-MOVD/MOVQ PINS BEGIN — GENERATED by hwprobe/mk_vexsilf_anchors.py; change mk_vexsilf_rows.py "
         "and regenerate⟧")
END = "-- ⟦D371 VEX-MOVD/MOVQ PINS END⟧"
TY = ("BitVec 256 × BitVec 256 × BitVec 256 × BitVec 64 × BitVec 64 × List (Nat × BitVec 64) × BitVec 64"
      " × BitVec 256 × BitVec 64 × List (Nat × BitVec 64)")

# vexsilf_ops.S's registers: the XMM destination %xmm3, the XMM source %xmm1, the GPR %eax/%rax, memory at (%rbx).
EA = "{ base := some .rbx }"


def instr(form, w, bs):
    """The Lean instruction vexsilf_ops.S executes; its length the declared bytes'."""
    n = len(bytearray.fromhex(bs))
    sz = ".d" if w == 32 else ".q"
    op = {"gx": ".vexmovg true %s .x3 .rax" % sz, "xg": ".vexmovg false %s .x1 .rax" % sz,
          "ld": ".vexmovgld %s .x3 %s" % (sz, EA), "st": ".vexmovgst %s %s .x1" % (sz, EA)}[form]
    return "⟨.vex (%s), %d⟩" % (op, n), n


def hx(v, digits):
    return "0x%0*x" % (digits, v)


def block():
    M.build()
    rs = list(M.ROWS)
    lines = [BEGIN]
    used = 0
    for fn, form, w, bs in M.OPS:
        ins, n = instr(form, w, bs)
        fam = [r for r in rs if r[1] == fn]
        if not fam:
            raise SystemExit("mk_vexsilf_anchors: %s has no rows" % fn)
        used += len(fam)
        lines += ["", "set_option maxRecDepth 8000 in", "theorem vf_%s_pins :" % fn[2:],
                  "  ([  -- all %d of hwprobe's %s rows · x86isa refuses %s (%s)" % (len(fam), fn, fn[2:7], form)]
        for i, (nm, _fn, _form, _w, y1, y2, y3, f, rax, mem, off, w3, wrax, wmem) in enumerate(fam):
            sep = "," if i + 1 < len(fam) else ""
            nb = _w // 8
            span = range(off // 8, (off + nb - 1) // 8 + 1)
            qs = lambda m: "[" + ", ".join("(%d, %s)" % (j, hx((m >> (64 * j)) & ((1 << 64) - 1), 16))
                                           for j in span) + "]"
            mq = qs(mem) if _form in ("ld", "st") else "[]"
            wq = qs(wmem) if _form == "st" else "[]"
            lines.append("    (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)%s  -- %s" % (
                hx(y1, 64), hx(y2, 64), hx(y3, 64), hx(f, 3), hx(rax, 16), mq, hx(off, 2), hx(w3, 64),
                hx(wrax, 16), wq, sep, nm))
        lines.append("  ] : List (%s)).all" % TY)
        lines += ["    (fun (y1, y2, y3, f, rax, mem, off, w3, wrax, wq) =>",
                  "      let t := step %s (vfPre y1 y2 y3 f rax mem off)" % ins,
                  "      vfAgrees t %d y1 y2 f w3 wrax wq) = true := by decide" % n]
    if used != len(rs):
        raise SystemExit("mk_vexsilf_anchors: %d of mk_vexsilf_rows.py's rows are not pinned" % (len(rs) - used))
    lines += ["", END]
    return lines


def extract(text):
    ls = text.split("\n")
    if BEGIN not in ls or END not in ls:
        return None
    i, j = ls.index(BEGIN), ls.index(END)
    return ls[i:j + 1] if i < j else None


def compare(text, want):
    got = extract(text)
    if got is None:
        return ["the generated block's markers (D371) are missing from Tests/AnchorsVexSilF.lean"]
    if got == want:
        return []
    bad = [k for k in range(max(len(got), len(want)))
           if k >= len(got) or k >= len(want) or got[k] != want[k]]
    return ["%d line(s) differ from the generator, first at block line %d" % (len(bad), bad[0])]


def selftest():
    want = block()
    text = open(ANCHORS, encoding="utf-8").read()
    row = next(l for l in want if l.endswith("-- " + M.PLANT_ROW))
    head, tail = row.rsplit(")", 1)
    planted = head[:-1] + ("0" if head[-1] != "0" else "1") + ")" + tail
    arms = [
        ("control: the tracked block is the generator's output", not compare(text, want)),
        ("the plant really changes the row (else the next arm proves nothing)", planted != row),
        ("a row's expected result is changed", bool(compare(text.replace(row, planted), want))),
        ("a row is dropped", bool(compare(text.replace(row + "\n", ""), want))),
        ("the END marker is lost", bool(compare(text.replace(END, "  --"), want))),
    ]
    ok = True
    for name, good in arms:
        print(("  ✔ " if good else "  ✖ ") + name)
        ok = ok and good
    print("✅ mk_vexsilf_anchors selftest" if ok else "⛔ mk_vexsilf_anchors selftest FAILED")
    return 0 if ok else 1


def main(argv):
    P.strict_flags(__file__, argv)
    if "--selftest" in argv:
        return selftest()
    if "--check" in argv:
        want = block()
        bad = compare(open(ANCHORS, encoding="utf-8").read(), want)
        for b in bad:
            print("⛔ " + b)
        if not bad:
            print("✅ Tests/AnchorsVexSilF.lean carries mk_vexsilf_anchors.py's block byte for byte (%d lines)" % len(want))
        return 1 if bad else 0
    print("\n".join(block()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
